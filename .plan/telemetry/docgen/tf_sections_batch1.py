sec("## 19. The FP8 special-value problem",
    "Three code paths handle FP8 special values and they do not agree.",
    "The mathematics layer treats E4M3 as OCP-compatible, with a finite maximum of 448",
    "and no infinity.",
    "The codec layer decodes the reserved NaN pattern as zero.",
    "The adapter layer treats the upper finite exponent values as infinity or NaN.",
    "These are three different answers to the same question.",
    "The OCP specification is unambiguous: E4M3 has a maximum finite magnitude of 448,",
    "no infinity encoding, and exactly two signed NaN encodings.",
    "Any implementation that disagrees with that will produce files that a conforming",
    "reader decodes differently.",
    "This is the kind of defect that only shows up when a file leaves the building, so",
    "the fix the research draft proposes is the right one: one canonical implementation,",
    "exhaustive tests over all 256 byte patterns, and shared conversion routines.",
    "Exhaustive means exhaustive, not sampled.",
    "Two hundred and fifty-six values is a small enough space to assert on completely,",
    "and a sampled test would have missed at least one of these three disagreements.")

