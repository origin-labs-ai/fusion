sec("## 17. The integer path",
    "`include/quant/int8_quant.h` and `src/kernel/int8_quant.cpp` implement the integer",
    "quantization primitives.",
    "The scheme is symmetric: the scale is derived from the maximum absolute value and",
    "the zero point is fixed at zero.",
    "The scale formula is `s = 127 / max(|x|)` and the code is `q = round(x * s)`.",
    "Granularity is available per tensor and per token.",
    "The per-token path computes rows as the first dimension when the rank is greater",
    "than one, which means a three-dimensional input is treated as batch rows rather",
    "than as batch-times-sequence rows.",
    "That is a real defect, recorded in the INT and FP research draft, because the",
    "advertised granularity is not the delivered granularity for rank-three inputs.",
    "The second and larger problem is architectural.",
    "The integer inference path quantizes the input and immediately dequantizes it back",
    "to floating point before running an ordinary forward pass.",
    "That is a simulation of integer inference, not integer inference.",
    "The fix is not a small patch; it needs an integer-times-integer accumulation path",
    "with a controlled rescale into the output dtype.",
    "The plan's own gate list treats this as a first-class P0 item, which is the right",
    "place for it.")

