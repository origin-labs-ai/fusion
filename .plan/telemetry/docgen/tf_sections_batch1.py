sec("## 13. The block codec",
    "`include/quant/block_codec.h` and `src/codec/block_codec.cpp` implement the format",
    "that most of the ladder is built on.",
    "A block codec stores a header plus a run of codes plus, for the groupwise formats,",
    "per-group metadata.",
    "The block size is the unit of everything: scale selection, error bounds and tail",
    "handling are all defined relative to it.",
    "A tail block - the last block of a tensor when the size does not divide evenly -",
    "is the place where most format bugs live.",
    "The engine handles tails by falling back to a raw representation for the remainder,",
    "which keeps the decoder simple at the cost of a slightly worse ratio on the tail.",
    "That trade is visible in the measured budgets and it is deliberate.",
    "The codec is also where the compression accounting happens.",
    "When the project says a format costs 2.625 bits per weight, that number is the",
    "sum of the code bits and the amortised header and metadata bits, computed by the",
    "codec rather than asserted in a document.",
    "The master plan flags the `Q_16` family as needing documentation work, because its",
    "full-block path is a custom range reconstruction built from the block's FP32",
    "minimum and maximum rather than IEEE FP16 storage.",
    "That distinction matters: the tail fallback is FP16, the full block is not.",
    "A reader who assumes IEEE storage throughout will mis-predict the byte cost of a",
    "half-full tensor.",
    "The codec layer is therefore the layer where naming honesty is enforced.")

